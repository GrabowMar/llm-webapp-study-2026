import { expect, test } from "@playwright/test";

test("public recipes, filtering, details and mobile layout", async ({ page }) => {
  const errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.goto("/");
  await expect(page.getByRole("heading", { name: "A little inspiration. A lot of good food." })).toBeVisible();
  await expect(page.locator("article")).toHaveCount(5);
  await page.screenshot({ path: "test-results/table-thyme-desktop.png", fullPage: true });
  await page.getByRole("button", { name: "Dinner", exact: true }).click();
  await expect(page.locator("article")).toHaveCount(2);
  await page.getByRole("searchbox", { name: "Search recipe titles" }).fill("pasta");
  await expect(page.locator("article")).toHaveCount(1);
  await page.getByRole("heading", { name: "Creamy tomato & basil pasta" }).click();
  await expect(page.getByRole("heading", { name: "A few good ingredients" })).toBeVisible();
  await expect(page.locator("li")).toHaveCount(8);
  await expect(page.getByRole("button", { name: "Edit recipe" })).toHaveCount(0);
  await page.reload();
  await expect(page.getByRole("heading", { name: "Creamy tomato & basil pasta" })).toBeVisible();
  await page.getByRole("button", { name: "Back to the recipe book" }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.locator("article")).toHaveCount(5);
  await expect(page.getByRole("button", { name: "Add", exact: true })).toBeVisible();
  await page.screenshot({ path: "test-results/table-thyme-mobile.png", fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  expect(errors).toEqual([]);
});

test("register, validation, add, edit, delete, and sign out", async ({ page }) => {
  await page.goto("/");
  await page.getByRole("button", { name: "Share your favorite" }).click();
  await page.getByRole("button", { name: "Create your account" }).click();
  await expect(page.getByText("Password must be between 8 and 128 characters.")).toBeVisible();
  const username = `cook${Date.now()}`;
  await page.getByLabel("Username", { exact: true }).fill(username);
  await page.getByLabel("Password", { exact: true }).fill("a-good-secret-password");
  await page.getByRole("button", { name: "Create your account" }).click();
  await expect(page.getByRole("heading", { name: "Something worth sharing." })).toBeVisible();
  await page.getByRole("button", { name: "Share your recipe", exact: true }).click();
  await expect(page.getByText("Each ingredient must contain 1–500 characters. Remove unused rows.")).toBeVisible();
  await page.getByLabel("Recipe title").fill("Browser test soup");
  await page.getByLabel("Category", { exact: true }).fill("Lunch");
  await page.getByLabel("Ingredient 1", { exact: true }).fill("1 onion");
  await page.getByLabel("Ingredient 2", { exact: true }).fill("500 ml stock");
  await page.getByRole("button", { name: "Add an ingredient" }).click();
  await page.getByLabel("Ingredient 3", { exact: true }).fill("1 carrot");
  await page.getByRole("button", { name: "Remove ingredient 2" }).click();
  await page.getByLabel("Instructions", { exact: true }).fill("Chop everything.\n\nSimmer gently.");
  await page.getByRole("button", { name: "Share your recipe", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Browser test soup" })).toBeVisible();
  await expect(page.locator("li")).toHaveText(["1 onion", "1 carrot"]);
  await page.reload();
  await expect(page.getByRole("button", { name: "Edit recipe" })).toBeVisible();
  await page.getByRole("button", { name: "Edit recipe" }).click();
  await page.getByLabel("Recipe title").fill("Better browser test soup");
  await page.getByRole("button", { name: "Save changes" }).click();
  await expect(page.getByRole("heading", { name: "Better browser test soup" })).toBeVisible();
  await page.getByRole("button", { name: "Delete", exact: true }).click();
  await page.getByRole("button", { name: "Keep recipe" }).click();
  await expect(page.getByRole("heading", { name: "Better browser test soup" })).toBeVisible();
  await page.getByRole("button", { name: "Delete", exact: true }).click();
  await page.getByRole("button", { name: "Delete recipe", exact: true }).click();
  await expect(page.locator("article")).toHaveCount(5);
  await page.getByRole("button", { name: "Sign out", exact: true }).click();
  await expect(page.getByRole("button", { name: "Sign in", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Sign in", exact: true }).click();
  await page.getByLabel("Username", { exact: true }).fill(username);
  await page.getByLabel("Password", { exact: true }).fill("a-good-secret-password");
  await page.getByRole("dialog").getByRole("button", { name: "Sign in", exact: true }).click();
  await expect(page.getByText(username, { exact: true })).toBeVisible();
});
